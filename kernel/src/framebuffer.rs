// kernel/src/framebuffer.rs - GOP Framebuffer Console Driver
//
// Provides pixel-based text rendering for UEFI GOP framebuffers.
// Uses an embedded 8x16 bitmap font for character rendering.
// Supports scrolling, cursor tracking, and basic color output.

use core::fmt;
use crate::boot_info;

const CHAR_WIDTH: u32 = 8;
const CHAR_HEIGHT: u32 = 16;

// Colors (ARGB 32-bit format, matching typical UEFI GOP pixel layout)
const COLOR_BG: u32 = 0x00000000;     // Black background
const COLOR_FG: u32 = 0x00AAAAAA;     // Light gray text (standard VGA gray)
const COLOR_BRIGHT: u32 = 0x00FFFFFF; // White (bright)
const COLOR_GREEN: u32 = 0x0000FF00;  // Green
const COLOR_RED: u32 = 0x00FF0000;    // Red
const COLOR_CYAN: u32 = 0x0000FFFF;   // Cyan

pub struct FramebufferWriter {
    fb_addr: u64,
    width: u32,
    height: u32,
    pitch: u32,  // bytes per scanline
    cols: u32,   // text columns
    rows: u32,   // text rows
    cur_col: u32,
    cur_row: u32,
    fg_color: u32,
    initialized: bool,
}

pub static mut FB_WRITER: FramebufferWriter = FramebufferWriter {
    fb_addr: 0,
    width: 0,
    height: 0,
    pitch: 0,
    cols: 0,
    rows: 0,
    cur_col: 0,
    cur_row: 0,
    fg_color: COLOR_FG,
    initialized: false,
};

impl FramebufferWriter {
    pub fn init_from_boot_info(&mut self) {
        let info = boot_info::get_boot_info();
        self.fb_addr = info.framebuffer_addr;
        self.width = info.framebuffer_width;
        self.height = info.framebuffer_height;
        self.pitch = info.framebuffer_pitch;
        self.cols = self.width / CHAR_WIDTH;
        self.rows = self.height / CHAR_HEIGHT;
        self.cur_col = 0;
        self.cur_row = 0;
        self.fg_color = COLOR_FG;

        if self.fb_addr != 0 && self.width > 0 && self.height > 0 {
            self.initialized = true;
            self.clear();
        }
    }

    pub fn is_initialized(&self) -> bool {
        self.initialized
    }

    pub fn clear(&mut self) {
        if !self.initialized { return; }
        unsafe {
            let fb = self.fb_addr as *mut u32;
            let pixels_per_line = self.pitch / 4;
            for y in 0..self.height {
                for x in 0..self.width {
                    *fb.add((y * pixels_per_line + x) as usize) = COLOR_BG;
                }
            }
        }
        self.cur_col = 0;
        self.cur_row = 0;
    }

    fn put_pixel(&self, x: u32, y: u32, color: u32) {
        if x >= self.width || y >= self.height { return; }
        unsafe {
            let fb = self.fb_addr as *mut u32;
            let pixels_per_line = self.pitch / 4;
            *fb.add((y * pixels_per_line + x) as usize) = color;
        }
    }

    fn draw_char(&self, ch: u8, col: u32, row: u32, fg: u32) {
        let glyph = get_glyph(ch);
        let base_x = col * CHAR_WIDTH;
        let base_y = row * CHAR_HEIGHT;

        for dy in 0..CHAR_HEIGHT {
            let bits = glyph[dy as usize];
            for dx in 0..CHAR_WIDTH {
                let color = if (bits >> (7 - dx)) & 1 == 1 { fg } else { COLOR_BG };
                self.put_pixel(base_x + dx, base_y + dy, color);
            }
        }
    }

    fn scroll_up(&mut self) {
        if !self.initialized { return; }
        unsafe {
            let fb = self.fb_addr as *mut u8;
            let line_bytes = self.pitch;
            let char_line_bytes = (CHAR_HEIGHT * line_bytes) as usize;
            let total_text_bytes = ((self.rows - 1) * CHAR_HEIGHT * line_bytes) as usize;

            // Shift everything up by one character row
            core::ptr::copy(
                fb.add(char_line_bytes),
                fb,
                total_text_bytes,
            );

            // Clear the last row
            let last_row_start = total_text_bytes;
            core::ptr::write_bytes(
                fb.add(last_row_start),
                0,
                char_line_bytes,
            );
        }
    }

    fn newline(&mut self) {
        self.cur_col = 0;
        self.cur_row += 1;
        if self.cur_row >= self.rows {
            self.scroll_up();
            self.cur_row = self.rows - 1;
        }
    }

    pub fn write_byte(&mut self, byte: u8) {
        if !self.initialized { return; }

        match byte {
            b'\n' => self.newline(),
            b'\r' => { self.cur_col = 0; }
            0x08 => {
                // Backspace
                if self.cur_col > 0 {
                    self.cur_col -= 1;
                    self.draw_char(b' ', self.cur_col, self.cur_row, COLOR_BG);
                }
            }
            byte => {
                if self.cur_col >= self.cols {
                    self.newline();
                }
                self.draw_char(byte, self.cur_col, self.cur_row, self.fg_color);
                self.cur_col += 1;
            }
        }
    }

    pub fn write_string(&mut self, s: &str) {
        for byte in s.bytes() {
            self.write_byte(byte);
        }
    }
}

impl fmt::Write for FramebufferWriter {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        self.write_string(s);
        Ok(())
    }
}

