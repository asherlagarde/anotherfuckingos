/// Get the 8x16 glyph bitmap for a character (16 bytes, one per row)
fn get_glyph(ch: u8) -> &'static [u8; 16] {
    if ch >= 32 && ch <= 126 {
        &FONT_8X16[(ch - 32) as usize]
    } else {
        &FONT_8X16[0] // space for unknown chars
    }
}

